// Writes README.md from profile.config.mjs. Don't edit README.md by hand; edit the config and run this.
//   node studio/readme.mjs
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import profile from "../profile.config.mjs";
import { slugOf } from "./assets.mjs";

const p = profile;
const on = (k) => p.sections[k] ?? true;
const live = `https://${p.github.toLowerCase()}.github.io/${p.repo}/live/`;
const starIssue = `https://github.com/${p.github}/${p.repo}/issues/new?title=galaxy%3A+leave+a+star&body=Just+hit+%22Create%22.+A+bot+will+add+your+star+to+the+galaxy+and+close+this+issue+in+about+a+minute.+%E2%9C%A6`;
const strip = (html) => html.replace(/<[^>]+>/g, "");
const header = (k) => `<img src="assets/Design/h-${k}.svg" width="100%" alt="${p.headers[k][0]}: ${p.headers[k][1]}" />`;
const gap = "<br />";

const blocks = [];

blocks.push(`<!-- Generated by studio/readme.mjs from profile.config.mjs. Edit the config, not this file. -->

<a href="${live}">
  <img src="assets/Design/hero.webp" width="100%" alt="${p.name}, ${p.title}. ${strip(p.taglines[0])}" />
</a>

<p align="center">
  <a href="${live}"><img src="assets/Design/cta-play.svg" height="48" alt="Play with the 3D core" /></a>
</p>

<p align="center">
${p.socials.map((s) => `  <a href="${s.url}"><img src="assets/Design/social-${slugOf(s.label)}.svg" height="44" alt="${s.label}" /></a>`).join("\n")}
</p>`);

if (on("about")) blocks.push(`${header("about")}

<img src="assets/Design/about.svg" width="100%" alt="${p.name}, ${p.about.role} at ${p.about.company}, ${p.about.location}. ${p.about.intro}" />`);

if (on("platform")) blocks.push(`${header("platform")}

<img src="assets/Design/platform.svg" width="100%" alt="${p.platform.stages.map((s) => `${s.title}: ${s.lines.join(", ")}`).join("; ")}" />`);

if (on("projects")) blocks.push(`${header("projects")}

<p align="center">
${p.projects.map((pr) => `  <a href="https://github.com/${pr.repo}"><img src="assets/Design/card-${pr.id}.webp" width="49%" alt="${pr.title}: ${pr.desc}" /></a>`).join("\n")}
</p>`);

if (on("stack")) blocks.push(`${header("stack")}

${p.stacks.map((s) => `<img src="assets/Design/stack-${s.slug}.svg" width="${Math.round((Math.max(s.items.length * 78 - 14, 600) / 1000) * 100)}%" alt="${s.title}: ${s.items.map((i) => i[0]).join(", ")}" />`).join(`\n${gap}\n`)}`);

if (on("galaxy")) blocks.push(`${header("galaxy")}

<a href="${starIssue}">
  <img src="assets/Design/galaxy.svg" width="100%" alt="Galaxy guestbook: every visitor who says hi becomes a named star" />
</a>

<p align="center">
  <a href="${starIssue}"><img src="assets/Design/cta-star.svg" height="48" alt="Leave your star in the galaxy" /></a>
</p>`);

if (on("stats")) {
  const snake = on("snake") ? `

<picture>
  <source media="(prefers-color-scheme: dark)" srcset="https://raw.githubusercontent.com/${p.github}/${p.repo}/output/snake-dark.svg" />
  <source media="(prefers-color-scheme: light)" srcset="https://raw.githubusercontent.com/${p.github}/${p.repo}/output/snake-light.svg" />
  <img src="https://raw.githubusercontent.com/${p.github}/${p.repo}/output/snake-dark.svg" width="100%" alt="Snake eating the contribution graph" />
</picture>` : "";
  blocks.push(`${header("stats")}

<p align="center">
  <img src="assets/Dynamic/isocalendar.svg" width="49%" alt="Contribution calendar" />
  <img src="assets/Dynamic/languages.svg" width="49%" alt="Most used languages" />
</p>${snake}

<details>
  <summary><b>More stats</b>: activity, PRs, achievements, topics</summary>
  <br />
  <p align="center">
    <img src="assets/Dynamic/stats.svg" width="100%" alt="GitHub stats" />
    <img src="assets/Dynamic/issuesPRs.svg" width="100%" alt="Issues and pull requests" />
    <img src="assets/Dynamic/achievements.svg" width="100%" alt="Achievements" />
    <img src="assets/Dynamic/topics.svg" width="100%" alt="Topics" />
    <img src="assets/Dynamic/reactions.svg" width="100%" alt="Reactions" />
  </p>
</details>`);
}

if (on("dailyBreak")) blocks.push(`<details>
  <summary><b>Daily break</b>: today's cartoon and joke</summary>
  <br />
  <p align="center">
    <img src="assets/Dynamic/cartoon.svg" width="600" alt="Cartoon of the day" />
    <img src="assets/Dynamic/joke.svg" width="600" alt="Joke of the day" />
  </p>
</details>`);

blocks.push(`<img src="assets/Design/divider.svg" width="100%" alt="" />

<p align="center">
  <sub>Rendered in three.js, recorded frame by frame, kept alive by GitHub Actions. <a href="docs/GUIDE.md">Make one like it</a>.</sub>${on("viewCounter") ? `
  <br />
  <img src="https://komarev.com/ghpvc/?username=${p.github}&style=flat-square&color=a78bfa&label=profile+views" alt="Profile views" />` : ""}
</p>`);

writeFileSync(resolve(import.meta.dirname, "..", "README.md"), blocks.join(`\n\n${gap}\n\n`) + "\n");
console.log("readme: README.md written");
